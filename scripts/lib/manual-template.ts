// Builds data/manual/YYYY-MM.yaml (spec Section 11.2): one entry per MANUAL/SEMI metric, plus any
// AUTO metric the fetchers could not refresh, pre-filled with last edition's values marked stale.

import fs from "node:fs";
import path from "node:path";
import { formatValue } from "../../lib/format";
import type { MetricConfig, MetricSeed } from "../../lib/types";
import {
  autoUsable,
  editionLabel,
  loadAutoAt,
  loadEditionAt,
  loadMetricsConfigAt,
  manualFile,
  previousEditionId,
} from "./io";
import { expectedRelease } from "./release-timing";

const q = (s: string) => JSON.stringify(s); // a JSON string is a valid YAML scalar
const num = (n: number | null | undefined) => (n == null ? "null" : String(n));

function header(id: string, prevId: string | null, autoNote: string): string {
  return `# Manual figures for the ${editionLabel(id)} edition (${id}).
# Generated by: npm run manual-template -- ${id}
# Pre-filled from the ${prevId ?? "(no previous)"} edition. Every entry starts with "stale: true".
# ${autoNote}
#
# HOW TO FILL THIS IN (GitHub web editor, about 30 minutes)
#   1. On GitHub, open this file in the pull request's branch and click the pencil icon (Edit).
#   2. For each entry below that says "stale: true":
#        - Click (copy) the source_url and find the newest number. "expected_release" says when it is usually out.
#        - Update value, period, period_label, as_of, and year_ago / year_ago_period (the same period one
#          year earlier, as the source reports it). Type plain numbers: 4.1 not "4.1%", 416700 not "$416,700".
#        - If the source moved, update source_url too.
#        - Change "stale: true" to "stale: false".
#   3. No new release this month? Leave the old numbers, set "carry_forward: true" and write a short reason,
#      e.g. carry_forward_reason: "NY Fed publishes quarterly; Q3 not out until Dec 4". The site keeps
#      showing the old value with its original "as of" date.
#   4. Unknown year-ago value? Use null (no arrow is shown). Never estimate or round differently than the source.
#   5. "display" (only where present) is the exact text shown on the page, e.g. "3.75–4.00%".
#      Update it together with value, or delete the line to use the standard format.
#   6. Click "Commit changes...", choose "Commit directly to the ... branch". The checks re-run automatically.
#
# The build fails while any entry marked "required: true" is still "stale: true" without
# "carry_forward: true" and a reason (spec 11.2). Arrows and colors are computed; never type them.
`;
}

function entryYaml(id: string, cfg: MetricConfig, prev: MetricSeed | undefined, reason: string): string {
  const L: string[] = [];
  L.push(`  # ${cfg.label} · ${cfg.automation} · ${reason}${cfg.required ? " · REQUIRED" : ""}`);
  L.push(`  ${id}:`);
  L.push(`    label: ${q(cfg.label)}`);
  L.push(`    required: ${cfg.required ? "true" : "false"}`);
  L.push(`    stale: true            # set to false once this month's number is entered`);
  L.push(`    value: ${num(prev?.value)}`);
  // Only carry a display text when it is a real override (differs from the standard format).
  if (prev?.display && prev.value != null && prev.display !== formatValue(prev.value, cfg)) {
    L.push(`    display: ${q(prev.display)}     # update together with value, or delete this line`);
  }
  L.push(`    period: ${q(prev?.period ?? "")}`);
  L.push(`    period_label: ${q(prev?.period_label ?? "")}`);
  L.push(`    year_ago: ${num(prev?.year_ago)}`);
  if (prev?.year_ago_display && prev.year_ago != null && prev.year_ago_display !== formatValue(prev.year_ago, cfg)) {
    L.push(`    year_ago_display: ${q(prev.year_ago_display)}`);
  } else if (prev?.year_ago_display && prev.year_ago == null) {
    L.push(`    year_ago_display: ${q(prev.year_ago_display)}`);
  }
  L.push(`    year_ago_period: ${q(prev?.year_ago_period ?? "")}`);
  if (prev?.change_reported) {
    const c = prev.change_reported;
    const parts = [
      c.pct != null ? `pct: ${c.pct}` : null,
      c.points != null ? `points: ${c.points}` : null,
      c.approx ? "approx: true" : null,
    ].filter(Boolean);
    L.push(`    change_reported: { ${parts.join(", ")} }   # y/y change as the source reports it (when no year-ago level)`);
  }
  L.push(`    as_of: ${q(prev?.as_of ?? prev?.period ?? "")}`);
  L.push(`    source_url: ${q(prev?.source_url ?? cfg.source_url)}`);
  if (prev?.notes) L.push(`    notes: ${q(prev.notes)}`);
  if (prev?.footnote) L.push(`    footnote: ${q(prev.footnote)}`);
  L.push(`    expected_release: ${q(expectedRelease(id, cfg))}`);
  L.push(`    carry_forward: false`);
  L.push(`    carry_forward_reason: ""`);
  return L.join("\n");
}

export interface TemplateResult {
  file: string;
  written: boolean;
  ids: string[];
  message: string;
}

/** Writes the template unless the file already exists (never overwrites the owner's entries). */
export function makeManualTemplate(root: string, id: string): TemplateResult {
  const file = manualFile(root, id);
  if (fs.existsSync(file)) {
    return { file, written: false, ids: [], message: `${path.relative(root, file)} already exists; not overwriting it.` };
  }
  const cfg = loadMetricsConfigAt(root);
  const prevId = previousEditionId(root, id);
  const prev = prevId ? loadEditionAt(root, prevId) : null;
  const auto = loadAutoAt(root, id);

  const entries: { id: string; yaml: string }[] = [];
  for (const [mid, c] of Object.entries(cfg.metrics)) {
    let reason: string | null = null;
    if (c.automation !== "AUTO") reason = "entered by hand";
    else if (!auto) reason = "auto.json missing";
    else if (!autoUsable(auto.metrics[mid])) {
      const a = auto.metrics[mid];
      reason = a?.error ? `fetch failed: ${a.error}` : a ? "fetch came back stale" : "not in auto.json";
    }
    if (!reason) continue;
    entries.push({ id: mid, yaml: entryYaml(mid, c, prev?.metrics[mid], reason) });
  }

  const autoNote = auto
    ? `AUTO metrics fetched fresh in data/raw/${id}/auto.json are not listed; only those that came back stale or failed.`
    : `data/raw/${id}/auto.json was not found, so every AUTO metric is listed too (normally they are fetched).`;
  const body = `${header(id, prevId, autoNote)}\nedition: ${q(id)}\nmetrics:\n${entries.map((e) => e.yaml).join("\n\n")}\n`;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body);
  return {
    file,
    written: true,
    ids: entries.map((e) => e.id),
    message: `Wrote ${path.relative(root, file)} with ${entries.length} entries (pre-filled from ${prevId ?? "nothing"}).`,
  };
}
